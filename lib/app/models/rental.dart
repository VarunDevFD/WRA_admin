class Product {
  final String name;
  final String description;
  final double price;
  final String imageUrl;
  final String category;
  final DateTime date;
  final String status;

  Product({
    required this.name,
    required this.description,
    required this.price,
    required this.imageUrl,
    required this.category,
    required this.date,
    required this.status,
  });
}
